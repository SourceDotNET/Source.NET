using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Source.CodeAnalysis.VGUI
{
	[Generator(LanguageNames.CSharp)]
	public sealed class PanelMessageMapGenerator : IIncrementalGenerator
	{
		const string Controls = "Source.GUI.Controls.";
		const string G = "global::";

		static readonly DiagnosticDescriptor UnsupportedHandler = new DiagnosticDescriptor(
			id: "VGUI002",
			title: "Unsupported message or command handler",
			messageFormat: "'{0}' cannot be used as a VGUI handler: {1}",
			category: "VGUI",
			defaultSeverity: DiagnosticSeverity.Error,
			isEnabledByDefault: true);

		public void Initialize(IncrementalGeneratorInitializationContext context) {
			context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) => Execute(spc, compilation));
		}

		sealed class Symbols
		{
			public INamedTypeSymbol Panel = null!;
			public INamedTypeSymbol UiMessage = null!;
			public INamedTypeSymbol UiCommand = null!;
			public INamedTypeSymbol? MessageParam;
			public INamedTypeSymbol? KeyValues;
			public INamedTypeSymbol? Color;
		}

		static void Execute(SourceProductionContext spc, Compilation compilation) {
			INamedTypeSymbol? panel = compilation.GetTypeByMetadataName(Controls + "Panel");
			INamedTypeSymbol? uiMessage = compilation.GetTypeByMetadataName(Controls + "UiMessageAttribute");
			INamedTypeSymbol? uiCommand = compilation.GetTypeByMetadataName(Controls + "UiCommandAttribute");
			if (panel == null || uiMessage == null || uiCommand == null || compilation.GetTypeByMetadataName(Controls + "PanelMessageMap") == null)
				return;

			Symbols s = new Symbols {
				Panel = panel,
				UiMessage = uiMessage,
				UiCommand = uiCommand,
				MessageParam = compilation.GetTypeByMetadataName(Controls + "MessageParamAttribute"),
				KeyValues = compilation.GetTypeByMetadataName("Source.Common.Formats.Keyvalues.KeyValues"),
				Color = compilation.GetTypeByMetadataName("System.Drawing.Color"),
			};

			List<INamedTypeSymbol> panels = new List<INamedTypeSymbol>();
			CollectPanels(compilation.Assembly.GlobalNamespace, s, panels);

			StringBuilder accessors = new StringBuilder();
			StringBuilder body = new StringBuilder();
			int accessorId = 0;

			foreach (INamedTypeSymbol type in panels)
				Handlers(spc, type, s, accessors, body, ref accessorId);

			if (body.Length == 0)
				return;

			StringBuilder sb = new StringBuilder();
			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("#nullable enable");
			sb.AppendLine("#pragma warning disable CA2255");
			sb.AppendLine();
			sb.AppendLine("namespace Source.Generated;");
			sb.AppendLine();
			sb.AppendLine("internal static class VGuiPanelMessageMaps");
			sb.AppendLine("{");
			sb.Append(accessors);
			sb.AppendLine("\t[global::System.Runtime.CompilerServices.ModuleInitializer]");
			sb.AppendLine("\tinternal static void Register() {");
			sb.Append(body);
			sb.AppendLine("\t}");
			sb.AppendLine("}");

			spc.AddSource("VGuiPanelMessageMaps.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
		}

		static void CollectPanels(INamespaceOrTypeSymbol container, Symbols s, List<INamedTypeSymbol> panels) {
			foreach (ISymbol member in container.GetMembers()) {
				if (member is INamespaceSymbol ns)
					CollectPanels(ns, s, panels);
				else if (member is INamedTypeSymbol type) {
					if (type.TypeKind == TypeKind.Class && DerivesFrom(type, s.Panel))
						panels.Add(type);
					CollectPanels(type, s, panels);
				}
			}
		}

		static bool IsGeneric(INamedTypeSymbol type) {
			for (INamedTypeSymbol? t = type; t != null; t = t.ContainingType)
				if (t.IsGenericType)
					return true;
			return false;
		}

		static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType) {
			for (INamedTypeSymbol? t = type; t != null; t = t.BaseType)
				if (SymbolEqualityComparer.Default.Equals(t, baseType))
					return true;
			return false;
		}

		static bool IsAccessible(INamedTypeSymbol type) {
			for (INamedTypeSymbol? t = type; t != null; t = t.ContainingType) {
				Accessibility a = t.DeclaredAccessibility;
				if (a != Accessibility.Public && a != Accessibility.Internal && a != Accessibility.ProtectedOrInternal)
					return false;
			}
			return true;
		}

		static void Handlers(SourceProductionContext spc, INamedTypeSymbol type, Symbols s, StringBuilder accessors, StringBuilder body, ref int accessorId) {
			string typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

			foreach (IMethodSymbol method in type.GetMembers().OfType<IMethodSymbol>()) {
				if (method.MethodKind != MethodKind.Ordinary)
					continue;

				List<string> messages = AttributeStrings(method, s.UiMessage);
				List<string> commands = AttributeStrings(method, s.UiCommand);
				if (messages.Count == 0 && commands.Count == 0)
					continue;

				if (IsGeneric(type) || !IsAccessible(type)) {
					spc.ReportDiagnostic(Diagnostic.Create(UnsupportedHandler, method.Locations.FirstOrDefault(), method.ToDisplayString(), "the containing panel must be a non-generic type accessible from generated code"));
					continue;
				}

				if (method.IsStatic || method.IsGenericMethod || method.Parameters.Any(p => p.RefKind != RefKind.None)) {
					spc.ReportDiagnostic(Diagnostic.Create(UnsupportedHandler, method.Locations.FirstOrDefault(), method.ToDisplayString(), "handlers must be non-generic instance methods without ref, in or out parameters"));
					continue;
				}

				string accessor = "__Handler" + accessorId++;
				string returnType = method.ReturnsVoid ? "void" : method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
				string parameters = string.Concat(method.Parameters.Select(p => ", " + p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + " " + p.Name));
				accessors.AppendLine($"\t[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = {Literal(method.Name)})]");
				accessors.AppendLine($"\tstatic extern {returnType} {accessor}({typeName} owner{parameters});");
				accessors.AppendLine();

				if (commands.Count > 0) {
					string? senderArg = null;
					if (method.Parameters.Length == 1)
						senderArg = SenderArgument(method.Parameters[0], s);

					if (method.Parameters.Length > 1 || (method.Parameters.Length == 1 && senderArg == null)) {
						spc.ReportDiagnostic(Diagnostic.Create(UnsupportedHandler, method.Locations.FirstOrDefault(), method.ToDisplayString(), "command handlers take no parameters or only the sender panel"));
						continue;
					}

					string commandCall = $"{accessor}(({typeName})p{(senderArg != null ? ", " + senderArg : "")})";
					foreach (string command in commands)
						body.AppendLine($"\t\t{G}Source.GUI.Controls.PanelMessageMap.AddCommandHandler(typeof({typeName}), {Literal(command)}, static (p, sender) => {commandCall});");
				}

				if (messages.Count > 0) {
					List<string> args = new List<string>();
					string? error = null;
					foreach (IParameterSymbol parameter in method.Parameters) {
						string? arg = Argument(parameter, s);
						if (arg == null) {
							error = $"parameter '{parameter.Name}' of type '{parameter.Type.ToDisplayString()}' cannot be read from a message";
							break;
						}
						args.Add(arg);
					}

					if (error != null) {
						spc.ReportDiagnostic(Diagnostic.Create(UnsupportedHandler, method.Locations.FirstOrDefault(), method.ToDisplayString(), error));
						continue;
					}

					string call = $"{accessor}(({typeName})p{string.Concat(args.Select(a => ", " + a))})";
					foreach (string message in messages)
						body.AppendLine($"\t\t{G}Source.GUI.Controls.PanelMessageMap.AddMessageHandler(typeof({typeName}), {Literal(message)}, static (p, m, sender) => {call});");
				}
			}
		}

		static List<string> AttributeStrings(ISymbol symbol, INamedTypeSymbol? attributeType) {
			List<string> values = new List<string>();
			if (attributeType == null)
				return values;

			foreach (AttributeData attribute in symbol.GetAttributes()) {
				if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, attributeType) && attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string value)
					values.Add(value);
			}
			return values;
		}

		static string? SenderArgument(IParameterSymbol parameter, Symbols s) {
			ITypeSymbol type = parameter.Type;
			if (parameter.Ordinal != 0 || !(type is INamedTypeSymbol panelType) || !DerivesFrom(panelType, s.Panel))
				return null;

			string typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
			bool nullable = type.NullableAnnotation == NullableAnnotation.Annotated;
			return $"({typeName})sender{(nullable ? "" : "!")}";
		}

		static string? Argument(IParameterSymbol parameter, Symbols s) {
			ITypeSymbol type = parameter.Type;
			string typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
			bool nullable = type.NullableAnnotation == NullableAnnotation.Annotated;

			string? sender = SenderArgument(parameter, s);
			if (sender != null)
				return sender;

			List<string> keys = AttributeStrings(parameter, s.MessageParam);
			if (keys.Count == 0 && s.KeyValues != null && SymbolEqualityComparer.Default.Equals(type.WithNullableAnnotation(NullableAnnotation.NotAnnotated), s.KeyValues))
				return "m";

			string key = Literal(keys.Count > 0 ? keys[0] : parameter.Name);

			switch (type.SpecialType) {
				case SpecialType.System_Int32: return $"m.GetInt({key})";
				case SpecialType.System_Boolean: return $"m.GetInt({key}) != 0";
				case SpecialType.System_Single: return $"m.GetFloat({key})";
				case SpecialType.System_Double: return $"(double)m.GetFloat({key})";
				case SpecialType.System_UInt64: return $"m.GetUint64({key})";
				case SpecialType.System_String: return $"new string(m.GetString({key}))";
				case SpecialType.System_Char:
				case SpecialType.System_SByte:
				case SpecialType.System_Byte:
				case SpecialType.System_Int16:
				case SpecialType.System_UInt16:
				case SpecialType.System_UInt32:
					return $"({typeName})m.GetInt({key})";
			}

			if (type.TypeKind == TypeKind.Enum)
				return $"({typeName})m.GetInt({key})";

			if (s.Color != null && SymbolEqualityComparer.Default.Equals(type, s.Color))
				return $"m.GetColor({key})";

			if (type is INamedTypeSymbol named && named.IsGenericType && named.ConstructedFrom.ToDisplayString() == "System.ReadOnlySpan<T>" && named.TypeArguments[0].SpecialType == SpecialType.System_Char)
				return $"m.GetString({key})";

			if (type.IsReferenceType)
				return $"({typeName})m.GetPtr({key}){(nullable ? "" : "!")}";

			return null;
		}

		static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
	}
}
