using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Source.CodeAnalysis.VGUI
{
	[Generator(LanguageNames.CSharp)]
	public sealed class PanelRegistrationGenerator : IIncrementalGenerator
	{
		const string Controls = "Source.GUI.Controls.";
		const string G = "global::";

		static readonly DiagnosticDescriptor Inaccessible = new DiagnosticDescriptor(
			id: "VGUI001",
			title: "Panel type is not accessible to the generated registration",
			messageFormat: "'{0}' is a panel but is not accessible from generated code, so it is not registered",
			category: "VGUI",
			defaultSeverity: DiagnosticSeverity.Warning,
			isEnabledByDefault: true);

		public void Initialize(IncrementalGeneratorInitializationContext context) {
			context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) => Execute(spc, compilation));
		}

		sealed class Symbols
		{
			public INamedTypeSymbol Panel = null!;
			public INamedTypeSymbol AnimationVar = null!;
			public INamedTypeSymbol? AnimationVarAlias;
			public INamedTypeSymbol? Alias;
		}

		static void Execute(SourceProductionContext spc, Compilation compilation) {
			INamedTypeSymbol? panel = compilation.GetTypeByMetadataName(Controls + "Panel");
			INamedTypeSymbol? animationVar = compilation.GetTypeByMetadataName(Controls + "PanelAnimationVarAttribute");
			if (panel == null || animationVar == null || compilation.GetTypeByMetadataName(Controls + "PanelRegistry") == null)
				return;

			Symbols s = new Symbols {
				Panel = panel,
				AnimationVar = animationVar,
				AnimationVarAlias = compilation.GetTypeByMetadataName(Controls + "PanelAnimationVarAliasTypeAttribute"),
				Alias = compilation.GetTypeByMetadataName(Controls + "PanelAliasAttribute"),
			};

			List<INamedTypeSymbol> panels = new List<INamedTypeSymbol>();
			CollectPanels(compilation.Assembly.GlobalNamespace, s, panels);
			if (panels.Count == 0)
				return;

			StringBuilder accessors = new StringBuilder();
			StringBuilder body = new StringBuilder();
			int accessorId = 0;

			foreach (INamedTypeSymbol type in panels) {
				if (!IsAccessible(type)) {
					spc.ReportDiagnostic(Diagnostic.Create(Inaccessible, type.Locations.FirstOrDefault(), type.ToDisplayString()));
					continue;
				}

				string typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
				string factory = Factory(type, s, typeName, accessors, ref accessorId);
				string alias = AliasOf(type, s);
				string animationVars = AnimationVars(type, s, typeName, accessors, ref accessorId);

				body.AppendLine($"\t\t{G}Source.GUI.Controls.PanelRegistry.Add(typeof({typeName}), {Literal(type.Name)}, {factory}, {alias}, {animationVars});");
			}

			StringBuilder sb = new StringBuilder();
			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("#nullable enable");
			sb.AppendLine("#pragma warning disable CA2255");
			sb.AppendLine();
			sb.AppendLine("namespace Source.Generated;");
			sb.AppendLine();
			sb.AppendLine("internal static class VGuiPanelRegistration");
			sb.AppendLine("{");
			sb.Append(accessors);
			sb.AppendLine("\t[global::System.Runtime.CompilerServices.ModuleInitializer]");
			sb.AppendLine("\tinternal static void Register() {");
			sb.Append(body);
			sb.AppendLine("\t}");
			sb.AppendLine("}");

			spc.AddSource("VGuiPanelRegistration.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
		}

		static void CollectPanels(INamespaceOrTypeSymbol container, Symbols s, List<INamedTypeSymbol> panels) {
			foreach (ISymbol member in container.GetMembers()) {
				if (member is INamespaceSymbol ns)
					CollectPanels(ns, s, panels);
				else if (member is INamedTypeSymbol type) {
					if (type.TypeKind == TypeKind.Class && !IsGeneric(type) && DerivesFrom(type, s.Panel))
						panels.Add(type);
					CollectPanels(type, s, panels);
				}
			}
		}

		static bool IsGeneric(INamedTypeSymbol type) {
			for (INamedTypeSymbol? t = type; t != null; t = t.ContainingType)
				if (t.IsGenericType)
					return true;
			return false;
		}

		static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType) {
			for (INamedTypeSymbol? t = type; t != null; t = t.BaseType)
				if (SymbolEqualityComparer.Default.Equals(t, baseType))
					return true;
			return false;
		}

		static bool IsAccessible(INamedTypeSymbol type) {
			for (INamedTypeSymbol? t = type; t != null; t = t.ContainingType) {
				Accessibility a = t.DeclaredAccessibility;
				if (a != Accessibility.Public && a != Accessibility.Internal && a != Accessibility.ProtectedOrInternal)
					return false;
			}
			return true;
		}

		static string Factory(INamedTypeSymbol type, Symbols s, string typeName, StringBuilder accessors, ref int accessorId) {
			IMethodSymbol? create = type.GetMembers("Create_" + type.Name).OfType<IMethodSymbol>()
				.FirstOrDefault(m => m.IsStatic && m.Parameters.Length == 0 && m.ReturnType is INamedTypeSymbol r && DerivesFrom(r, s.Panel));
			if (create != null) {
				string accessor = "__Create" + accessorId++;
				string returnType = create.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
				accessors.AppendLine($"\t[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = {Literal(create.Name)})]");
				accessors.AppendLine($"\tstatic extern {returnType} {accessor}({typeName}? owner);");
				accessors.AppendLine();
				return $"static () => {accessor}(null)";
			}

			if (!type.IsAbstract && type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public))
				return $"static () => new {typeName}()";

			return "null";
		}

		static string AliasOf(INamedTypeSymbol type, Symbols s) {
			if (s.Alias == null)
				return "null";

			AttributeData? attribute = type.GetAttributes().FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, s.Alias));
			if (attribute == null || attribute.ConstructorArguments.Length != 1 || !(attribute.ConstructorArguments[0].Value is string alias))
				return "null";

			return Literal(alias);
		}

		static string AnimationVars(INamedTypeSymbol type, Symbols s, string typeName, StringBuilder accessors, ref int accessorId) {
			StringBuilder calls = new StringBuilder();

			foreach (IFieldSymbol field in type.GetMembers().OfType<IFieldSymbol>()) {
				if (field.IsStatic || field.IsImplicitlyDeclared)
					continue;

				AttributeData? attribute = FindAttribute(field, s.AnimationVarAlias) ?? FindAttribute(field, s.AnimationVar);
				if (attribute == null)
					continue;

				string? name = null;
				string? defaultValue = null;
				string? typeAlias = null;
				var args = attribute.ConstructorArguments;
				if (args.Length == 1) {
					defaultValue = args[0].Value as string;
				}
				else if (args.Length == 2) {
					name = args[0].Value as string;
					defaultValue = args[1].Value as string;
				}
				else if (args.Length == 3) {
					name = args[0].Value as string;
					defaultValue = args[1].Value as string;
					typeAlias = args[2].Value as string;
				}

				string fieldType = field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
				string accessor = "__Field" + accessorId++;
				accessors.AppendLine($"\t[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = {Literal(field.Name)})]");
				accessors.AppendLine($"\tstatic extern ref {fieldType} {accessor}({typeName} owner);");
				accessors.AppendLine();

				calls.AppendLine($"\t\t\t{G}Source.GUI.Controls.Panel.AddToAnimationMap(typeof({typeName}), {Literal(name ?? field.Name)}, {Literal(typeAlias ?? TypeName(field.Type))}, {Literal(field.Name)}, {Literal(defaultValue ?? "")}, false,");
				calls.AppendLine($"\t\t\t\tstatic p => {accessor}(({typeName})p),");
				calls.AppendLine($"\t\t\t\tstatic (p, v) => {accessor}(({typeName})p) = ({fieldType})v);");
			}

			if (calls.Length == 0)
				return "null";

			return "static () => {\n" + calls + "\t\t}";
		}

		static AttributeData? FindAttribute(IFieldSymbol field, INamedTypeSymbol? attributeType) {
			if (attributeType == null)
				return null;
			return field.GetAttributes().FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, attributeType));
		}

		static string TypeName(ITypeSymbol type) {
			switch (type.SpecialType) {
				case SpecialType.System_SByte: return "sbyte";
				case SpecialType.System_Byte: return "byte";
				case SpecialType.System_Int16: return "short";
				case SpecialType.System_UInt16: return "ushort";
				case SpecialType.System_Int32: return "int";
				case SpecialType.System_UInt32: return "uint";
				case SpecialType.System_Int64: return "long";
				case SpecialType.System_UInt64: return "ulong";
				case SpecialType.System_Single: return "float";
				case SpecialType.System_Double: return "double";
			}
			if (type is IArrayTypeSymbol array)
				return array.ElementType.MetadataName + "[]";
			return type.MetadataName;
		}

		static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
	}
}
