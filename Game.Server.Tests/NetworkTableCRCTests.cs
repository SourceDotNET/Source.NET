	[UnsafeAccessor(UnsafeAccessorKind.StaticMethod, Name = "ComputeCRC")]
	static extern uint ComputeCRC([UnsafeAccessorType("Source.Engine.EngineSendTable, Source.Engine")] object? engineSendTable, ReadOnlySpan<SendTable> tables);

	static List<SendTable> ServerClassTables() {
		foreach (Type type in typeof(Game.Server.BaseEntity).Assembly.GetTypes()) {
			if (type.GetField(nameof(ServerClass), BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly)?.FieldType == typeof(ServerClass))
				RuntimeHelpers.RunClassConstructor(type.TypeHandle);
		}

		List<SendTable> tables = [];
		for (ServerClass? serverClass = ServerClass.Head; serverClass != null; serverClass = serverClass.Next)
			tables.Add(serverClass.Table);
		return tables;
	}

	static void AddReachable(SendTable table, List<SendTable> tables, HashSet<SendTable> seen) {
		if (!seen.Add(table))
			return;
		tables.Add(table);
		for (int i = 0; i < table.Props?.Length; i++) {
			SendTable? subTable = table.Props[i].Type == SendPropType.DataTable ? table.Props[i].GetDataTable() : null;
			if (subTable != null)
				AddReachable(subTable, tables, seen);
		}
	}

	static string Format((string Table, int Props, uint CRC) entry)
		=> $"\t\t(\"{entry.Table}\", {entry.Props.ToString(CultureInfo.InvariantCulture)}, 0x{entry.CRC:X8}),";

	[Fact]
	public void SendTablesAreUnchanged() {
		List<SendTable> tables = [];
		HashSet<SendTable> seen = new(ReferenceEqualityComparer.Instance);
		foreach (SendTable table in ServerClassTables())
			AddReachable(table, tables, seen);

		var actual = tables.Select(table => (Table: table.NetTableName!, Props: table.Props?.Length ?? 0, CRC: ComputeCRC(null, [table]))).ToList();
		Dictionary<string, (string Table, int Props, uint CRC)> expected = ExpectedSendTables.ToDictionary(entry => entry.Table);

		var report = new StringBuilder();
		foreach (var entry in actual) {
			if (!expected.Remove(entry.Table, out var old))
				report.AppendLine("added:   " + Format(entry));
			else if (old != entry)
				report.AppendLine("changed: " + Format(old).Trim() + " -> " + Format(entry).Trim());
		}
		foreach (var entry in expected.Values)
			report.AppendLine("removed: " + Format(entry));

		Assert.True(report.Length == 0, report.ToString());
	}
